#!/usr/bin/env python3
"""Validate the offline event snapshot and generate C++ without network access."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def generate():
    data = json.loads((ROOT / 'data/events.json').read_text(encoding='utf-8'))
    assert data['scheduleBasis'] == 'UTC midnight; display and daily reset labels use Beijing UTC+8'
    assert len(data['rows']) == data['count']
    ids = set()
    def string(value):
        return 'u8' + json.dumps(value, ensure_ascii=False)
    def steps(values, phase_ids):
        for step in values:
            assert step['r'] in phase_ids and type(step['d']) is int and 0 < step['d'] <= 1440
        return '{' + ','.join('{' + str(s['r']) + ',' + str(s['d']) + '}' for s in values) + '}'
    rows=[]
    for event in data['rows']:
        assert re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*', event['id']) and event['id'] not in ids
        ids.add(event['id'])
        for field in ('name','nameEn','category','categoryEn'):
            assert isinstance(event[field],str) and event[field] and '<' not in event[field]
        assert event['nameEn'].isascii() and event['categoryEn'].isascii()
        phase_ids = {p['id'] for p in event['phases']}
        assert len(phase_ids) == len(event['phases']) and phase_ids
        phases=[]
        for phase in event['phases']:
            assert phase['name'] and phase['nameEn'] and phase['nameEn'].isascii()
            assert len(phase['color'])==3 and all(type(c) is int and 0 <= c <= 255 for c in phase['color'])
            assert all(re.fullmatch(r'\[&[A-Za-z0-9+/]+=*\]', code) for code in phase['waypoints'].split())
            phases.append('{' + str(phase['id']) + ',' + ','.join(string(phase[f]) for f in ('name','nameEn','waypoints'))
                          + ',{' + ','.join(map(str,phase['color'])) + '},' + str(phase['active']).lower() + '}')
        partial=steps(event['partial'],phase_ids)
        pattern=steps(event['pattern'],phase_ids)
        weekly=event.get('weeklyPartials',[])
        assert not weekly or len(weekly)==7
        weekly_cpp='{' + ','.join(steps(day,phase_ids) for day in weekly) + '}'
        rotation=event.get('rotation','')
        assert rotation in ('','zeghai-2018-05-10')
        if rotation:
            assert set(range(16)).issubset(phase_ids)
        else:
            for day in weekly or [event['partial']]:
                assert sum(s['d'] for s in day)>=1440 or event['pattern'], 'Incomplete event day: '+event['id']
        rows.append('    {' + ','.join(string(event[f]) for f in ('id','name','nameEn','category','categoryEn'))
                    + ',{' + ','.join(phases) + '},' + partial + ',' + pattern + ',' + weekly_cpp + ','
                    + str(bool(rotation)).lower() + ',' + str(event['approximate']).lower() + '},')
    return ('// Generated by tools/generate_events.py; edit data/events.json instead.\n#pragma once\n'
            '#include "event_schedule.h"\nnamespace world_timer::event_generated {\n'
            'inline constexpr const char* kSnapshotDate = ' + string(data['snapshotDate']) + ';\n'
            'inline const std::vector<EventRow> kEvents = {\n' + '\n'.join(rows) + '\n};\n}\n')

if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    output=ROOT/'src/event_data.generated.h'
    rendered=generate()
    if args.check:
        if not output.exists() or output.read_text(encoding='utf-8')!=rendered:
            raise SystemExit('Event header is stale; run python tools/generate_events.py')
        print('Event snapshot and generated header match')
    else:
        output.write_text(rendered,encoding='utf-8')
        print('Generated event header')
