#!/usr/bin/env python3
"""Validate the standalone schedule snapshot and generate C++ (no network)."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    data = json.loads((ROOT / "data/bosses.json").read_text(encoding="utf-8"))
    if data["timezone"] != "Asia/Shanghai":
        raise ValueError("Schedule timezone must be explicit")
    ids = set()
    rows = []
    for boss in data["bosses"]:
        if boss["id"] in ids:
            raise ValueError("Duplicate boss ID")
        ids.add(boss["id"])
        if not re.fullmatch(r"\[&[A-Za-z0-9+/]+=*\]", boss["point"]):
            raise ValueError("Invalid waypoint chat code")
        minutes = []
        for time in boss["times"]:
            if not re.fullmatch(r"(?:[01][0-9]|2[0-3]):[0-5][0-9]", time):
                raise ValueError("Invalid time: " + time)
            h, m = map(int, time.split(":"))
            minutes.append(h * 60 + m)
        if not minutes or minutes != sorted(set(minutes)):
            raise ValueError("Times must be sorted, unique and nonempty")
        fields = [boss[k] for k in ("id", "name", "map", "point", "zone")]
        if not all(isinstance(v, str) and v for v in fields):
            raise ValueError("Missing boss metadata")
        strings = ", ".join("u8" + json.dumps(v, ensure_ascii=False) for v in fields)
        english = [boss[k] for k in ("nameEn", "mapEn", "zoneEn")]
        if not all(isinstance(v, str) and v and v.isascii() for v in english):
            raise ValueError("Missing English metadata")
        english_strings = ", ".join(json.dumps(v) for v in english)
        rows.append("    {" + strings + ", {" + ", ".join(map(str, minutes)) + "}, " + english_strings + "},")
    if len(ids) != data["count"] or sum(len(b["times"]) for b in data["bosses"]) != data["timesCount"]:
        raise ValueError("Snapshot counts disagree")
    return ('// Generated by tools/generate_data.py; edit data/bosses.json instead.\n'
            '#pragma once\n#include "schedule.h"\n\nnamespace world_timer::generated {\n'
            'inline constexpr const char* kSnapshotDate = ' + json.dumps(data["snapshotDate"]) + ';\n'
            'inline const std::vector<Boss> kBosses = {\n' + '\n'.join(rows)
            + '\n};\n} // namespace world_timer::generated\n')


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "src/boss_data.generated.h"
    rendered = generate()
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != rendered:
            raise SystemExit("Generated header is stale; run python3 tools/generate_data.py")
        print("Schedule snapshot and generated header match")
    else:
        output.write_text(rendered, encoding="utf-8")
        print("Generated", output)
